# Мужское/женское по корневым разделам.
GENDER = [
    ("muzhskiie", r"для женщин|женский вибратор|вагинальн[ыо]", "в «Мужских», а по названию женский"),
    ("zhienskiie", r"для мужчин|мастурбатор|для члена|на член", "в «Женских», а по названию мужской"),
]

rows = []
for h, (pat, why) in CONTRA.items():
    rx = re.compile(pat, re.I)
    for p in in_col.get(h, []):
        if rx.search(p["title"]):
            rows.append((why, h, rx.search(p["title"]).group(0), p))
for h, pat, why in GENDER:
    rx = re.compile(pat, re.I)
    for p in in_col.get(h, []):
        if rx.search(p["title"]):
            rows.append((why, h, rx.search(p["title"]).group(0), p))

g = defaultdict(list)
for why, h, hit, p in rows:
    g[(why, h)].append((hit, p))
total = 0
for (why, h), items in sorted(g.items(), key=lambda x: -len(x[1])):
    total += len(items)
    print(f"\n— {why}  [{h}] — {len(items)}")
    for hit, p in items:
        st = "" if p["status"] == "ACTIVE" else f" ({p['status']})"
        print(f"    {(p['sku'] or '—'):7s} {p['title'][:68]:68s} «{hit}»{st}")
print(f"\n===== противоречий: {total}")
